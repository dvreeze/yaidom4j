package eu.cdevreeze.yaidom4j.internal;

import org.jspecify.annotations.Nullable;

/**
 * Poor man's alternative to Guava's Preconditions class (in the absence of a Guava dependency).
 * Good enough as internal API, but unfit as general "preconditions" utility.
 *
 * @author Chris de Vreeze
 */
public class PreconditionUtil {

    private PreconditionUtil() {
        // Non-instantiable
    }

    public static void checkArgument(boolean expression) {
        if (!expression) {
            throw new IllegalArgumentException();
        }
    }

    public static void checkArgument(boolean expression, @Nullable Object errorMessage) {
        if (!expression) {
            throw new IllegalArgumentException(String.valueOf(errorMessage));
        }
    }
}
